/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_FDCAN1_Init();
  MX_USB_DRD_FS_PCD_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_TIM3_Init();
  MX_TIM4_Init();
  MX_TIM15_Init();
  MX_ADC1_Init();
  MX_FDCAN2_Init();
  MX_RTC_Init();
  MX_TIM6_Init();
  /* USER CODE BEGIN 2 */

  HAL_ADCEx_Calibration_Start(&hadc1);

  HAL_ADC_Start_DMA(&hadc1, (uint32_t *)adc_buf, 4);

  HAL_PWR_EnableBkUpAccess();

  led_state = HAL_RTCEx_BKUPRead(&hrtc, RTC_BKP_DR0);

  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_1);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_2);
  HAL_TIM_PWM_Start(&htim1, TIM_CHANNEL_3);



  LV3_CAN_Init(8, LV3_CAN_BusMode_Normal, lv3_can_bindings, lv3_can_bindings_count);

  GPIO_PinState last_button_state = HAL_GPIO_ReadPin(BTN_USR_GPIO_Port, BTN_USR_Pin);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    // --- Read inputs ---
    V_SENSE_5  = adc_buf[0];
    V_SENSE_12 = adc_buf[1];

    float adc_pin_voltage;

    adc_pin_voltage = (V_SENSE_5 / (4095.0f * 64.0f / 4.0f)) * 3.3f;
    v_sense_5 = adc_pin_voltage * (1.0f + 1.0f) / 1.0f;

    adc_pin_voltage = (V_SENSE_12 / (4095.0f * 64.0f / 4.0f)) * 3.3f;
    v_sense_12 = adc_pin_voltage * (100.0f + 5.1f) / 5.1f;

    in_1 = HAL_GPIO_ReadPin(IN_1_GPIO_Port, IN_1_Pin);
    in_10 = HAL_GPIO_ReadPin(IN_10_GPIO_Port, IN_10_Pin);

    // --- Process state ---

    // RPM: below minimum speed (no pulse within timeout) reports zero. Above
    // that, use pulse counting over the update window at high speed (where
    // enough pulses land per window for good precision) and fall back to the
    // last measured inter-pulse period at low speed (too few pulses/window).
    uint32_t rpm_now = HAL_GetTick();
    if (rpm_now - rpm_last_pulse_tick >= RPM_TIMEOUT_MS) {
      rpm = 0.0f;
      rpm_pulse_count = 0;
      rpm_update_tick = rpm_now;
    } else if (rpm_now - rpm_update_tick >= RPM_UPDATE_INTERVAL_MS) {
      __disable_irq();
      uint32_t count = rpm_pulse_count;
      rpm_pulse_count = 0;
      uint32_t period_ms = rpm_last_period_ms;
      __enable_irq();

      uint32_t window_ms = rpm_now - rpm_update_tick;
      rpm_update_tick = rpm_now;

      if (count >= RPM_MIN_COUNT_FOR_FREQ) {
        rpm = ((float)count / RPM_PULSES_PER_REV) * (60000.0f / (float)window_ms);
      } else if (period_ms > 0) {
        rpm = 60000.0f / ((float)period_ms * RPM_PULSES_PER_REV);
      }
    }

    speed_mph = rpm * RPM_TO_MPH_SCALE;
    speed_mph_filtered += SPEED_MPH_IIR_ALPHA * (speed_mph - speed_mph_filtered);

    // --- LV3 CAN ---
    motor_rpm_val = (uint32_t)lroundf(rpm);
    motor_speed_val = (uint32_t)lroundf(speed_mph_filtered);
    LV3_CAN_Loop();

    // Toggle OUT_1 every 1s
    if (HAL_GetTick() - out_1_toggle_tick >= 1000) {
      out_1_toggle_tick = HAL_GetTick();
      out_1_state ^= 1;
    }

    GPIO_PinState button_state = HAL_GPIO_ReadPin(BTN_USR_GPIO_Port, BTN_USR_Pin);
    if (button_state == GPIO_PIN_SET && last_button_state == GPIO_PIN_RESET) {
      led_state ^= 1;
      HAL_RTCEx_BKUPWrite(&hrtc, RTC_BKP_DR0, led_state);
    }
    last_button_state = button_state;

    // --- Apply outputs ---
    HAL_GPIO_WritePin(OUT_1_GPIO_Port, OUT_1_Pin, out_1_state);
    // __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_1, in_1*100);
    // __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, led_state*100);
    __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_3, in_10*100);
  }
  /* USER CODE END 3 */
}

