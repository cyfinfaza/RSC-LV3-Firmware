// --- RPM (IN_10 pulse input) ---
// Adaptive: at high speed enough pulses land in each update window to count
// them (averages out HAL_GetTick()'s 1ms quantization); at low speed too few
// pulses land per window, so fall back to timing the single last inter-pulse
// period instead.
#define RPM_PULSES_PER_REV      48u   // pulses per wheel revolution
#define RPM_UPDATE_INTERVAL_MS  100u  // recompute rpm at this rate
#define RPM_TIMEOUT_MS          500u  // no pulse for this long => report 0 RPM
#define RPM_MIN_COUNT_FOR_FREQ  2u    // below this many pulses/window, use period instead

volatile uint32_t rpm_pulse_count = 0;     // pulses since last RPM update
volatile uint32_t rpm_last_pulse_tick = 0; // tick of most recent pulse
volatile uint32_t rpm_last_period_ms = 0;  // ms between the last two pulses

uint32_t rpm_update_tick = 0;
float rpm = 0.0f;

// --- Speed (derived from RPM and wheel size) ---
#define WHEEL_DIAMETER_IN  21.5f  // configurable wheel diameter, inches
// mph = rpm * (pi * diameter) [inches/rev] * 60 [min/hr] / 63360 [inches/mile]
#define RPM_TO_MPH_SCALE   60.0f * (WHEEL_DIAMETER_IN * 3.14159265f / 12.0f / 5280.0f)

float speed_mph = 0.0f;

// Basic first-order IIR (exponential moving average) low-pass on the speed
// output, to smooth out the update-to-update noise from the RPM calc.
#define SPEED_MPH_IIR_ALPHA  0.2f  // 0-1; smaller = smoother but slower to respond
float speed_mph_filtered = 0.0f;

// --- LV3 CAN bindings (module id 8, rounded to nearest integer) ---
uint32_t motor_rpm_val = 0;
uint32_t motor_speed_val = 0;

const LV3_CAN_Binding lv3_can_bindings[] = {
    {&motor_rpm_val,   motor_rpm,   LV3_CAN_BindMode_Write},
    {&motor_speed_val, motor_speed, LV3_CAN_BindMode_Write},
};
const unsigned int lv3_can_bindings_count = sizeof(lv3_can_bindings) / sizeof(LV3_CAN_Binding);
